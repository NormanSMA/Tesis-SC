// Genera prisma/migrations/<AAAAMMDDHHMMSS>_<nombre>/migration.sql.
// Contenido: diff de Prisma + prisma/sql/restricciones.sql sin BEGIN ni COMMIT.
// Uso: node scripts/db/generar-migracion.mjs <nombre> [--desde-vacio] [--sin-restricciones]
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

const raiz = path.resolve(import.meta.dirname, "..", "..");
const carpetaMigraciones = path.join(raiz, "prisma", "migrations");
const esquema = path.join(raiz, "prisma", "schema.prisma");
const restricciones = path.join(raiz, "prisma", "sql", "restricciones.sql");

const argumentos = process.argv.slice(2);
const banderas = new Set(argumentos.filter((a) => a.startsWith("--")));
const nombre = argumentos.find((a) => !a.startsWith("--"));

if (!nombre || !/^[a-z0-9_]+$/.test(nombre)) {
  console.error("Uso: node scripts/db/generar-migracion.mjs <nombre_en_minusculas> [--desde-vacio] [--sin-restricciones]");
  process.exit(1);
}

function marcaDeTiempo() {
  return new Date().toISOString().replace(/\D/g, "").slice(0, 14);
}

function ejecutarDiff(destino, desdeVacio) {
  const origen = desdeVacio ? ["--from-empty"] : ["--from-config-datasource"];
  const env = { ...process.env };
  // Con --from-empty Prisma no abre la base, pero la configuracion exige la variable.
  if (desdeVacio && !env.DATABASE_URL_MIGRACION) {
    env.DATABASE_URL_MIGRACION = "postgresql://sin:uso@127.0.0.1:1/sin_uso";
  }
  // pnpm exec fija NODE_PATH. Sin el, prisma.config.ts no resuelve dotenv.
  const argumentosPrisma = ["migrate", "diff", ...origen, "--to-schema", `"${esquema}"`, "--script", "-o", `"${destino}"`];
  const resultado = spawnSync(`pnpm exec prisma ${argumentosPrisma.join(" ")}`, {
    cwd: raiz,
    env,
    stdio: ["ignore", "inherit", "inherit"],
    shell: true,
  });
  if (resultado.status !== 0) {
    console.error("prisma migrate diff fallo.");
    process.exit(resultado.status ?? 1);
  }
}

function leerRestricciones() {
  const sinTransaccion = /^\s*(BEGIN|COMMIT);\s*$/;
  return readFileSync(restricciones, "utf8")
    .split(/\r?\n/)
    .filter((linea) => !sinTransaccion.test(linea))
    .join("\n");
}

function armarSql(diffPrisma) {
  const partes = [diffPrisma.trimEnd()];
  if (!banderas.has("--sin-restricciones")) {
    partes.push("-- Restricciones de prisma/sql/restricciones.sql (idempotentes)", leerRestricciones().trim());
  }
  return partes.join("\n\n") + "\n";
}

const temporal = mkdtempSync(path.join(tmpdir(), "sc-migracion-"));
try {
  const archivoDiff = path.join(temporal, "diff.sql");
  ejecutarDiff(archivoDiff, banderas.has("--desde-vacio"));
  const carpeta = path.join(carpetaMigraciones, `${marcaDeTiempo()}_${nombre}`);
  mkdirSync(carpeta, { recursive: true });
  writeFileSync(path.join(carpeta, "migration.sql"), armarSql(readFileSync(archivoDiff, "utf8")));
  const bloqueo = path.join(carpetaMigraciones, "migration_lock.toml");
  if (!existsSync(bloqueo)) {
    writeFileSync(bloqueo, '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n');
  }
  console.log(`Migracion creada: ${path.relative(raiz, carpeta)}`);
} finally {
  rmSync(temporal, { recursive: true, force: true });
}

// Login sin sesión, buscador global y selector de cliente del drawer: node captura-extras.mjs <carpeta> <ancho>
import { createRequire } from "node:module";
import { mkdirSync, readFileSync } from "node:fs";
import path from "node:path";

const repo = "C:/Proyectos/sc-plataforma";
const require = createRequire(path.join(repo, "package.json"));
const { chromium } = require("@playwright/test");
const [salida, anchoTexto] = process.argv.slice(2);
const ancho = Number(anchoTexto);
const movil = ancho < 500;
mkdirSync(salida, { recursive: true });
const clave = readFileSync(path.join(repo, ".env.example"), "utf8").match(/^SEED_PASSWORD_ATENCION_CLIENTE=(.*)$/m)[1].trim().replace(/^"|"$/g, "");
const navegador = await chromium.launch();
const pagina = await (await navegador.newContext({ viewport: { width: ancho, height: movil ? 844 : 900 }, isMobile: movil, hasTouch: movil, locale: "es-NI" })).newPage();
await pagina.goto("http://127.0.0.1:3000/login"); await pagina.waitForTimeout(800);
await pagina.screenshot({ path: path.join(salida, `login-${ancho}.png`) });
await pagina.getByLabel("Correo electrónico").fill("valentina.castro@solucionescreativas.test");
await pagina.locator("#contrasena").fill(clave);
await pagina.getByRole("button", { name: "Ingresar" }).click();
await pagina.waitForURL((url) => !url.pathname.startsWith("/login"));
await pagina.waitForTimeout(600);
if (movil) await pagina.getByRole("button", { name: "Abrir menú de navegación" }).click();
await pagina.getByRole("button", { name: "Buscar en TRACORE" }).last().click(); await pagina.waitForTimeout(400);
await pagina.screenshot({ path: path.join(salida, `buscador-vacio-${ancho}.png`) });
await pagina.keyboard.type("hotel"); await pagina.waitForTimeout(900);
await pagina.screenshot({ path: path.join(salida, `buscador-hotel-${ancho}.png`) });
await pagina.keyboard.press("Escape");
await pagina.goto("http://127.0.0.1:3000/cotizaciones?crear=1"); await pagina.waitForTimeout(1200);
await pagina.locator("#clienteId").click(); await pagina.waitForTimeout(300);
await pagina.keyboard.type("cole"); await pagina.waitForTimeout(700);
await pagina.screenshot({ path: path.join(salida, `selector-cliente-${ancho}.png`) });
await pagina.keyboard.type("gio inexistente"); await pagina.waitForTimeout(900);
await pagina.screenshot({ path: path.join(salida, `selector-cliente-crear-${ancho}.png`) });
await navegador.close();
console.log(`extras ${ancho} ok`);
